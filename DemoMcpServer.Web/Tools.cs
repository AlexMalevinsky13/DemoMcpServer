using ModelContextProtocol.Server;
using System.ComponentModel;

namespace DemoMcpServer.Web;

[McpServerToolType]
public static class DemoTools
{
    [McpServerTool]
    [Description("Returns the current server time in UTC.")]
    public static string GetServerTime() =>
         DateTimeOffset.UtcNow.ToString("O");

    [McpServerTool]
    [Description("Adds two integer numbers and returns their sum.")]
    public static int AddNumbers([Description("First number")] int a, [Description("Second number")] int b) =>
        checked(a + b);

    [McpServerTool]
    [Description("Returns a greeting for the specified person.")]
    public static string SayHello([Description("Person's name")] string name) =>
        $"Hello, {name}! Response generated by .NET 10 MCP Server.";
}